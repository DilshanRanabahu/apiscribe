"""Assemble the OpenAPI 3 document and write it as YAML."""

from __future__ import annotations

import re
from http import HTTPStatus

import yaml

from apiscribe.paths import Endpoint
from apiscribe.schema import infer, infer_from_strings, merge_all

OPENAPI_VERSION = "3.0.3"
NON_TAG_SEGMENT_RE = re.compile(r"^(api|rest|v\d+(\.\d+)*)$", re.I)


def build(endpoints: list[Endpoint], title: str) -> dict:
    """Build the OpenAPI document as a plain dict."""
    servers = sorted({ex.base_url for e in endpoints for ex in e.exchanges})
    paths: dict[str, dict] = {}
    security_schemes: dict[str, dict] = {}
    operation_ids: set[str] = set()

    for endpoint in endpoints:
        for ex in endpoint.exchanges:
            for name, scheme in ex.security:
                security_schemes.setdefault(name, scheme)
        operation = _operation(endpoint, operation_ids)
        paths.setdefault(endpoint.path, {})[endpoint.method.lower()] = operation

    spec: dict = {
        "openapi": OPENAPI_VERSION,
        "info": {
            "title": title,
            "version": "1.0.0",
            "description": "Generated by apiscribe from recorded HTTP traffic. Review before publishing.",
        },
        "servers": [{"url": url} for url in servers],
        "paths": paths,
    }
    if security_schemes:
        spec["components"] = {"securitySchemes": dict(sorted(security_schemes.items()))}
    return spec


def to_yaml(spec: dict) -> str:
    return yaml.dump(spec, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True, width=120)


def write(spec: dict, path) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write(to_yaml(spec))


class _NoAliasDumper(yaml.SafeDumper):
    """Merged schemas share dict objects; without this PyYAML writes &id001 anchors."""

    def ignore_aliases(self, data) -> bool:
        return True


def _operation(endpoint: Endpoint, operation_ids: set[str]) -> dict:
    exchanges = endpoint.exchanges
    operation: dict = {"operationId": _operation_id(endpoint, operation_ids)}

    tag = _tag(endpoint.path)
    if tag:
        operation["tags"] = [tag]

    parameters = [
        {"name": name, "in": "path", "required": True, "schema": infer_from_strings(values)}
        for name, values in endpoint.path_params.items()
    ]
    query_names = list(dict.fromkeys(name for ex in exchanges for name in ex.query))
    for name in query_names:
        values = [ex.query[name] for ex in exchanges if name in ex.query]
        parameters.append(
            {
                "name": name,
                "in": "query",
                "required": len(values) == len(exchanges),
                "schema": infer_from_strings(values),
            }
        )
    if parameters:
        operation["parameters"] = parameters

    bodies = [ex.request_body for ex in exchanges if ex.request_body is not None]
    if bodies:
        operation["requestBody"] = {
            "required": len(bodies) == len(exchanges),
            "content": {"application/json": {"schema": merge_all(infer(b) for b in bodies)}},
        }

    operation["responses"] = _responses(endpoint)

    security = _security(endpoint)
    if security:
        operation["security"] = security
    return operation


def _responses(endpoint: Endpoint) -> dict:
    responses: dict[str, dict] = {}
    for status in sorted({ex.status for ex in endpoint.exchanges}):
        try:
            description = HTTPStatus(status).phrase
        except ValueError:
            description = "Response"
        response: dict = {"description": description}
        bodies = [ex.response_body for ex in endpoint.exchanges if ex.status == status and ex.response_body is not None]
        if bodies:
            response["content"] = {"application/json": {"schema": merge_all(infer(b) for b in bodies)}}
        responses[str(status)] = response
    return responses


def _security(endpoint: Endpoint) -> list[dict]:
    """Each scheme seen is an alternative; add {} if some calls had no auth at all."""
    names = sorted({name for ex in endpoint.exchanges for name, _ in ex.security})
    if not names:
        return []
    requirements: list[dict] = [{name: []} for name in names]
    if any(not ex.security for ex in endpoint.exchanges):
        requirements.append({})
    return requirements


def _operation_id(endpoint: Endpoint, used: set[str]) -> str:
    """GET /users/{user_id}/orders -> getUsersOrdersByUserId."""
    static, params = [], []
    for segment in endpoint.path.strip("/").split("/"):
        if not segment:
            continue
        target = params if segment.startswith("{") else static
        target.append(segment.strip("{}"))
    words = static or ["root"]
    if params:
        words = words + ["by"] + params
    camel = "".join(_camel_words(w) for w in words)
    base = endpoint.method.lower() + camel
    name, n = base, 2
    while name in used:
        name, n = f"{base}{n}", n + 1
    used.add(name)
    return name


def _camel_words(text: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", text) if w)


def _tag(path: str) -> str | None:
    """First meaningful static segment: /api/v1/orders/{id} -> orders."""
    for segment in path.strip("/").split("/"):
        if segment and not segment.startswith("{") and not NON_TAG_SEGMENT_RE.match(segment):
            return segment
    return None
